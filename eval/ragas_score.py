"""Score saved RAG samples with the official RAGAS Faithfulness metric (ragas 0.4).

RAGAS lives in its own virtual environment so its dependencies can't disturb the app:

    python -m venv .cache/ragas-venv
    .cache/ragas-venv/Scripts/python -m pip install ragas langchain-groq
    python -m eval.faithfulness --engine llm            # generates + saves the samples
    .cache/ragas-venv/Scripts/python eval/ragas_score.py eval/results/faithfulness_llm_llm.json

The judge is the same Groq model the app uses (GROQ_API_KEY / YM_GROQ_MODEL from .env), reached
through Groq's OpenAI-compatible endpoint.
"""
from __future__ import annotations

import asyncio
import json
import os
import sys
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parent.parent


def load_env() -> None:
    env = ROOT / ".env"
    if env.exists():
        for line in env.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                v = v.split(" #", 1)[0].strip().strip('"').strip("'")
                if v and not v.startswith("#"):
                    os.environ.setdefault(k.strip(), v)


async def main(path: Path) -> None:
    from openai import AsyncOpenAI
    from ragas.llms import llm_factory
    from ragas.metrics.collections import Faithfulness

    load_env()
    model = os.getenv("YM_GROQ_MODEL", "openai/gpt-oss-120b")
    client = AsyncOpenAI(api_key=os.environ["GROQ_API_KEY"], base_url="https://api.groq.com/openai/v1",
                         max_retries=8, timeout=180)
    judge = llm_factory(model, provider="openai", client=client, temperature=0, max_tokens=8000)
    metric = Faithfulness(llm=judge)

    samples = json.loads(path.read_text(encoding="utf-8"))
    scores = []
    for i, s in enumerate(samples, 1):
        try:
            ctx = s["contexts"] + ([f"What the citizen told us about themselves:\n{s['citizen_facts']}"]
                                   if s.get("citizen_facts") else [])
            r = await metric.ascore(user_input=s["question"], response=s["answer"], retrieved_contexts=ctx)
            s["ragas_faithfulness"] = float(r.value)
        except Exception as e:  # keep going; report failures separately
            s["ragas_faithfulness"] = None
            s["ragas_error"] = f"{type(e).__name__}: {e}"[:300]
        scores.append(s["ragas_faithfulness"])
        print(f"[{i}/{len(samples)}] {s['id']}: {s['ragas_faithfulness']}", flush=True)

    def avg(kind=None):
        xs = [s["ragas_faithfulness"] for s in samples
              if s["ragas_faithfulness"] is not None and (kind is None or s["kind"] == kind)]
        return (mean(xs), len(xs)) if xs else (float("nan"), 0)

    failed = sum(1 for x in scores if x is None)
    a, e, q = avg(), avg("explain"), avg("qa")
    md = [f"# RAGAS Faithfulness (ragas 0.4, judge: Groq {model})", "",
          f"Answers generated by: {', '.join(sorted({s['method'] for s in samples}))} · source: `{path.name}`", "",
          "| Set | RAGAS faithfulness | Scored |", "|---|---|---|",
          f"| All | {a[0]:.3f} | {a[1]} |", f"| Scheme explanations | {e[0]:.3f} | {e[1]} |",
          f"| Free-form Q&A | {q[0]:.3f} | {q[1]} |", "",
          f"Failed to score: {failed}", "", "## Lowest-scoring samples", ""]
    for s in sorted([s for s in samples if s["ragas_faithfulness"] is not None],
                    key=lambda s: s["ragas_faithfulness"])[:6]:
        md.append(f"- **{s['id']}** {s['ragas_faithfulness']:.2f}: {s['question']}")
    out = ROOT / "eval" / "results" / "faithfulness_ragas.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    (ROOT / "eval" / "results" / "faithfulness_ragas.json").write_text(
        json.dumps(samples, indent=2, ensure_ascii=False), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    asyncio.run(main(Path(sys.argv[1]) if len(sys.argv) > 1
                     else ROOT / "eval" / "results" / "faithfulness_llm_llm.json"))
